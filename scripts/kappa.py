"""
kappa.py
Inter-rater agreement between the two judges, for each guidelines version:
  - Cohen's kappa pooled across all criterion-level judgments
  - Cohen's kappa for each criterion separately
  - Cohen's kappa on the overall verdict (Pass / Send back / Fail)
  - a list of every disagreement with both judges' reasons

Makes no API calls. Results are written to agreement/kappa_results.md.

Usage (from the project root):
    python scripts/kappa.py
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCORES_DIR = ROOT / "results" / "scores"
RESULTS_FILE = ROOT / "agreement" / "kappa_results.md"

CRITERIA = {
    "v1": ["C1", "C2", "C3", "C4", "C5"],
    "v2": ["C1a", "C1b", "C2", "C3", "C4", "C5"],
}


def cohen_kappa(labels_a, labels_b):
    """Returns (observed agreement, chance agreement, kappa).
    Kappa is None when chance agreement is 1 (both raters used a single label
    throughout), because the formula would divide by zero."""
    n = len(labels_a)
    categories = set(labels_a) | set(labels_b)
    observed = sum(a == b for a, b in zip(labels_a, labels_b)) / n
    chance = sum(
        (labels_a.count(c) / n) * (labels_b.count(c) / n) for c in categories
    )
    if chance == 1:
        return observed, chance, None
    return observed, chance, (observed - chance) / (1 - chance)


def interpret(kappa):
    """Landis & Koch (1977) rule-of-thumb bands."""
    if kappa is None:
        return "undefined (no variation in scores)"
    if kappa > 0.80:
        return "almost perfect"
    if kappa > 0.60:
        return "substantial"
    if kappa > 0.40:
        return "moderate"
    if kappa > 0.20:
        return "fair"
    return "slight or none"


def format_row(label, n, observed, chance, kappa):
    kappa_text = "  n/a" if kappa is None else f"{kappa:5.2f}"
    return (
        f"  {label:<22}{n:>4}   {observed:6.1%}     {chance:6.1%}    "
        f"{kappa_text}   {interpret(kappa)}"
    )


def load_scores(version, judge):
    records = {}
    for score_file in sorted((SCORES_DIR / version / judge).glob("item_*.json")):
        record = json.loads(score_file.read_text(encoding="utf-8"))
        records[record["id"]] = record
    return records


def main():
    out = []
    disagreement_notes = []

    for version, criteria in CRITERIA.items():
        judge_a = load_scores(version, "judge_a")
        judge_b = load_scores(version, "judge_b")
        item_ids = sorted(set(judge_a) & set(judge_b))
        if not item_ids:
            out.append(f"GUIDELINES {version.upper()}: no scores found\n")
            continue

        out.append(f"GUIDELINES {version.upper()}  ({len(item_ids)} items, 2 judges)")
        out.append("")
        out.append(f"  {'level':<22}{'n':>4}   {'observed':>8}   {'by chance':>9}   {'kappa':>5}   reading")

        # Pooled: every criterion-level judgment treated as one observation
        pooled_a = [judge_a[i]["scores"][c]["score"] for i in item_ids for c in criteria]
        pooled_b = [judge_b[i]["scores"][c]["score"] for i in item_ids for c in criteria]
        out.append(format_row("All criteria pooled", len(pooled_a), *cohen_kappa(pooled_a, pooled_b)))

        # Each criterion on its own
        for c in criteria:
            labels_a = [judge_a[i]["scores"][c]["score"] for i in item_ids]
            labels_b = [judge_b[i]["scores"][c]["score"] for i in item_ids]
            out.append(format_row(c, len(labels_a), *cohen_kappa(labels_a, labels_b)))

        # Overall verdict (three categories)
        verdicts_a = [judge_a[i]["verdict"] for i in item_ids]
        verdicts_b = [judge_b[i]["verdict"] for i in item_ids]
        out.append(format_row("Overall verdict", len(verdicts_a), *cohen_kappa(verdicts_a, verdicts_b)))
        out.append("")

        # Collect disagreements with both reasons
        disagreement_notes.append(f"### Guidelines {version}")
        disagreement_notes.append("")
        found = False
        for i in item_ids:
            for c in criteria:
                a, b = judge_a[i]["scores"][c], judge_b[i]["scores"][c]
                if a["score"] != b["score"]:
                    found = True
                    disagreement_notes.append(f"**{i}, {c}**")
                    disagreement_notes.append(f"- judge_a scored {a['score']}: {a['reason']}")
                    disagreement_notes.append(f"- judge_b scored {b['score']}: {b['reason']}")
                    disagreement_notes.append("")
        if not found:
            disagreement_notes.append("No disagreements.")
            disagreement_notes.append("")

    text = "\n".join(out)
    print(text)

    md = [
        "# Inter-rater agreement",
        "",
        "Generated by `scripts/kappa.py`. Raters: judge_a (claude-sonnet-5) and "
        "judge_b (claude-opus-5), scoring the same 12 responses independently "
        "under each guidelines version.",
        "",
        "```",
        text,
        "```",
        "",
        "## Where the two judges disagreed, and why",
        "",
    ] + disagreement_notes
    RESULTS_FILE.write_text("\n".join(md), encoding="utf-8")
    print(f"Written to {RESULTS_FILE}")


if __name__ == "__main__":
    main()